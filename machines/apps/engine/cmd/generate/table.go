package main

import (
	"bytes"
	"go/format"
	"reflect"
	"slices"
	"strconv"
	"strings"

	"github.com/jterrazz/studio-station/apps/engine/catalog"
)

const tablePath = "apps/engine/catalog/builtin_table.go"

var catalogPath = reflect.TypeFor[catalog.Catalog]().PkgPath()

// value: the built-in catalog as Go: what the strict decoder reads from the
// embedded package files and Machinefiles, assembled and judged whole, so a
// run of station decodes none of them.
func builtinTable() []byte {
	c, err := catalog.Load(catalog.BuiltinFiles(), "packages")
	if err != nil {
		panic(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by `make generate` from the catalog's package files and Machinefiles. DO NOT EDIT.\n\n")
	b.WriteString("//go:build !catalog_yaml\n\npackage catalog\n\nfunc builtinCatalog() (Catalog, error) {\n\treturn ")
	goLiteral(&b, reflect.ValueOf(c), false, false)
	b.WriteString(", nil\n}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

// invariant: a value is written as the literal that builds it again, equal
// under reflect.DeepEqual: a nil slice or map stays nil, an empty one empty,
// and a value an interface or a pointer holds keeps its dynamic type.
func goLiteral(b *bytes.Buffer, v reflect.Value, typed, elided bool) {
	t := v.Type()
	switch v.Kind() {
	case reflect.Struct:
		if !elided {
			b.WriteString(goType(t))
		}
		b.WriteString("{")
		for i := range t.NumField() {
			if f := v.Field(i); !f.IsZero() {
				b.WriteString("\n" + t.Field(i).Name + ": ")
				goLiteral(b, f, false, false)
				b.WriteString(",")
			}
		}
		b.WriteString("}")
	case reflect.Pointer:
		switch {
		case v.IsNil():
			b.WriteString("nil")
		case v.Elem().Kind() == reflect.Struct:
			if !elided {
				b.WriteString("&")
			}
			goLiteral(b, v.Elem(), false, elided)
		default:
			b.WriteString("ref(")
			goLiteral(b, v.Elem(), true, false)
			b.WriteString(")")
		}
	case reflect.Slice, reflect.Array:
		if v.Kind() == reflect.Slice && v.IsNil() {
			b.WriteString("nil")
			return
		}
		b.WriteString(goType(t) + "{")
		for i := range v.Len() {
			b.WriteString("\n")
			goLiteral(b, v.Index(i), false, true)
			b.WriteString(",")
		}
		b.WriteString("}")
	case reflect.Map:
		if v.IsNil() {
			b.WriteString("nil")
			return
		}
		type entry struct {
			key string
			v   reflect.Value
		}
		var entries []entry
		it := v.MapRange()
		for it.Next() {
			var k bytes.Buffer
			goLiteral(&k, it.Key(), false, true)
			entries = append(entries, entry{k.String(), it.Value()})
		}
		slices.SortFunc(entries, func(a, b entry) int { return strings.Compare(a.key, b.key) })
		b.WriteString(goType(t) + "{")
		for _, e := range entries {
			b.WriteString("\n" + e.key + ": ")
			goLiteral(b, e.v, false, true)
			b.WriteString(",")
		}
		b.WriteString("}")
	case reflect.Interface:
		if v.IsNil() {
			b.WriteString("nil")
			return
		}
		goLiteral(b, v.Elem(), true, false)
	default:
		goScalar(b, v, typed)
	}
}

func goScalar(b *bytes.Buffer, v reflect.Value, typed bool) {
	var s string
	switch v.Kind() {
	case reflect.String:
		s = strconv.Quote(v.String())
	case reflect.Bool:
		s = strconv.FormatBool(v.Bool())
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		s = strconv.FormatInt(v.Int(), 10)
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		s = strconv.FormatUint(v.Uint(), 10)
	case reflect.Float32, reflect.Float64:
		s = strconv.FormatFloat(v.Float(), 'g', -1, 64)
	default:
		panic("the catalog table writes no " + v.Type().String())
	}
	if typed {
		s = goType(v.Type()) + "(" + s + ")"
	}
	b.WriteString(s)
}

func goType(t reflect.Type) string {
	if t.Name() != "" {
		if t.PkgPath() == "" || t.PkgPath() == catalogPath {
			return t.Name()
		}
		panic("the catalog table writes no type of another package: " + t.String())
	}
	switch t.Kind() {
	case reflect.Slice:
		return "[]" + goType(t.Elem())
	case reflect.Array:
		return "[" + strconv.Itoa(t.Len()) + "]" + goType(t.Elem())
	case reflect.Map:
		return "map[" + goType(t.Key()) + "]" + goType(t.Elem())
	case reflect.Pointer:
		return "*" + goType(t.Elem())
	case reflect.Interface:
		if t.NumMethod() == 0 {
			return "any"
		}
		panic("the catalog table writes no " + t.String())
	default:
		panic("the catalog table writes no " + t.String())
	}
}
