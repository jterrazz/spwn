package main

import (
	"path"
	"reflect"

	"github.com/jterrazz/studio-station/apps/engine/catalog"
	"github.com/jterrazz/studio-station/apps/engine/engine"
)

const (
	installPath         = "packages/api/install.json"
	installTypesPath    = "packages/api/install.d.ts"
	recordSchemaPath    = "packages/api/schemas/station.engine-record.v1.json"
	installedSchemaPath = "packages/api/schemas/station.install-record.v1.json"

	stateRootRule = "The state root is $XDG_STATE_HOME when it is an absolute path, else $HOME/.local/state."
)

type installRecord struct {
	Root   string `json:"root"`
	Path   string `json:"path"`
	Schema string `json:"schema"`
}

type install struct {
	Line      string        `json:"line"`
	Dir       string        `json:"dir"`
	Binary    string        `json:"binary"`
	Record    installRecord `json:"record"`
	Installed installRecord `json:"installed"`
}

// value: install.json, where station is installed, where the engine records
// the binary it runs from and where the public installer records the binary
// it installed, for a client with no engine to ask: the window reads it at
// its build.
func installTable() install {
	return install{
		Line: catalog.InstallLine, Dir: catalog.InstallDir, Binary: catalog.StationBinary,
		Record:    installRecord{Root: "state", Path: path.Join(catalog.StateFolder, engine.RecordFile), Schema: engine.RecordSchema},
		Installed: installRecord{Root: "state", Path: path.Join(catalog.StateFolder, engine.InstalledFile), Schema: engine.InstalledSchema},
	}
}

func installDeclaration() []byte {
	return []byte("// Generated by `make generate` (apps/engine/cmd/generate) from the catalog's install folder and the engine's records: do not edit.\n\n" +
		"// value: `~` is the home; `state` is $XDG_STATE_HOME when absolute, else $HOME/.local/state.\n" +
		"export type InstallRecord = { root: 'state'; path: string; schema: string };\n" +
		"export type Install = { line: string; dir: string; binary: string; record: InstallRecord; installed: InstallRecord };\n\n" +
		"declare const install: Install;\nexport default install;\n")
}

// invariant: the record's schema is projected from the Go type the engine
// writes and describes v1, its version a constant: the file is the same for
// every version, a later shape bumps v, and a reader that does not know a
// record's v ignores it and falls back to the install folder.
func recordSchema(w *wireRules) map[string]any {
	return recordShape(w, engine.RecordSchema, recordSchemaPath,
		"The binary the engine last started from, written to "+catalog.StateFolder+"/"+engine.RecordFile+" under the state root at each engine start, so a client finds station while the engine does not answer. "+stateRootRule+" Written by make generate from engine.Record; install.json says where.")
}

// invariant: the installer's record is the engine's Record under another
// schema id: one type, two files, so the window reads both the same way.
func installedSchema(w *wireRules) map[string]any {
	return recordShape(w, engine.InstalledSchema, installedSchemaPath,
		"The binary the public installer last installed, written atomically to "+catalog.StateFolder+"/"+engine.InstalledFile+" under the state root at the end of a successful install that installed a station binary, so a client finds station before any engine has started. A platform with no station build gets spwn alone, exits 0 and writes no record; an older record is left byte for byte and never deleted. An install path with a control character (below 0x20, or 0x7f) is refused before any write. "+stateRootRule+" The shape is engine.Record's, written by make generate; install.json says where.")
}

func recordShape(w *wireRules, id, schemaPath, description string) map[string]any {
	r := &reflector{defs: map[string]any{}, wire: w}
	doc := r.wireObject(reflect.TypeFor[engine.Record]())
	if props, ok := doc["properties"].(map[string]any); ok {
		props["v"] = map[string]any{"const": engine.RecordVersion}
	}
	out := map[string]any{
		"$schema":     draft,
		"$id":         "https://github.com/jterrazz/studio-station/blob/main/" + schemaPath,
		"title":       id,
		"description": description,
		"$defs":       r.defs,
	}
	for k, v := range doc {
		out[k] = v
	}
	return out
}
