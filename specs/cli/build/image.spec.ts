import { directory } from '@jterrazz/test';
import { execFileSync, spawnSync } from 'node:child_process';
import { afterEach, describe, expect, test } from 'vitest';

import { cli } from '../cli.specification.js';

// hazard: a document cannot ask Docker for the images a build tagged, nor remove them after

const build = cli.with({ env: { SPWN_BASE_IMAGE: 'spwn-test:latest' } });

const BUILT_TAGS = ['spwn-docker-pilot:latest', 'spwn-codex-pilot:test', 'spwn-test-qa:v1'];

const imageExists = (tag: string): boolean =>
    spawnSync('docker', ['image', 'inspect', tag], { encoding: 'utf8', timeout: 10_000 }).status ===
    0;

describe('image', () => {
    afterEach(() => {
        spawnSync('docker', ['rmi', '-f', ...BUILT_TAGS], { encoding: 'utf8', timeout: 30_000 });
    });

    test('build tags the project image after the project', async () => {
        // Given - the docker-pilot project built on the simulator base image
        await using result = await build
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .exec('build');

        // Then - the session reports the build and the tag is in Docker
        expect(result.exitCode).toBe(0);
        expect(result.stderr.grep('Built image')).toMatch(
            '  ✓  Built image\n     spwn-docker-pilot:latest',
        );
        expect(imageExists('spwn-docker-pilot:latest')).toBe(true);
    });

    test('--tag names the image', async () => {
        // Given - the docker-pilot project built with an explicit tag
        await using result = await build
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .exec('build --tag spwn-test-qa:v1');

        // Then - the session reports the build and the custom tag is in Docker
        expect(result.exitCode).toBe(0);
        expect(result.stderr.grep('Built image')).toMatch('  ✓  Built image\n     spwn-test-qa:v1');
        expect(imageExists('spwn-test-qa:v1')).toBe(true);
    });

    test('--json reports the image it built', async () => {
        // Given - the docker-pilot project built with --json
        await using result = await build
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .exec('build --json');

        // Then - the report names the base, the runtime, the tag, the image and the tree it compiled
        expect(result.exitCode).toBe(0);
        expect(result.json).toMatch({
            runtime: 'claude-code',
            world: 'neo',
            treeFiles: 2,
            treeOnly: false,
            tag: 'spwn-docker-pilot:latest',
            imageId: 'sha256:{{hex}}',
            baseImage: 'spwn-test:latest',
        });
    });

    test('a codex image holds AGENTS.md, the codex config and native skills, and nothing of Claude Code', async () => {
        // Given - the codex-pilot project built with a custom tag
        await using result = await build
            .fixture(directory('../__fixtures__/codex-pilot/'))
            .exec('build --tag spwn-codex-pilot:test');

        // Then - the agent's home inside the image, read with a one-shot container since a built image is no spawned one
        expect(result.exitCode).toBe(0);
        const home = execFileSync(
            'docker',
            [
                'run',
                '--rm',
                '--entrypoint',
                'sh',
                'spwn-codex-pilot:test',
                '-c',
                'cd /world/agents/neo && find . -type f | sort && cat .codex/config.toml',
            ],
            { encoding: 'utf8', timeout: 60_000 },
        );
        expect(home).toBe(
            './.agents/skills/focus/SKILL.md\n./.codex/config.toml\n./AGENTS.md\n# Generated by spwn. Do not edit by hand.\n# Source: spwn/hooks/*.yaml + spwn/agents/<name>/agent.yaml\n\nprofile = "neo"\n\n[profiles.neo]\nmodel = "gpt-5"\n\n',
        );
    });
});
