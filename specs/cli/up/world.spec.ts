import { directory, file } from '@jterrazz/test';
import { describe, expect, test } from 'vitest';

import { cli } from '../cli.specification.js';
import { worldOf } from './__setup__/world.js';

// hazard: a document cannot read a container back: its labels, mounts, network and agent home are the claim

describe('world', () => {
    test('up brings the agent online in a bounded, unprivileged world on the bridge network', async () => {
        // Given - the docker-pilot project brought up
        await using result = await cli
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .exec('up');

        // Then - the session, the world as Docker and the agent find it, and the prompt its runtime boots on
        expect(result.exitCode).toBe(0);
        // checker-disable-next-line ground-shared-or-inline -- a stream that opens on a line break and shares an indentation cannot be written in place: the comparison dedents such a literal, its quoted form included
        expect(result.stderr).toMatch(file('./__expected__/up.txt'));
        const neo = result.container('neo');
        await expect(worldOf(neo)).resolves.toStrictEqual({
            inside: 'spwn\n.claude\n.claude.json\nAGENTS.md\nCLAUDE.md\nSOUL.md\nagent.yaml\njournal\nplaybooks\nworlds\nknowledge\n/usr/bin/bash\n/usr/bin/git\n',
            labels: {
                config: 'neo',
                id: expect.stringMatching(/^world-neo-[0-9a-f]{5}$/u) as unknown,
                kind: 'world',
                runtime: 'claude-code',
            },
            mounts: [
                '/credentials ro',
                '/credentials/gh rw',
                '/workspaces/<project> rw',
                '/world/knowledge rw',
            ],
            network: 'bridge',
            pids: 256,
            running: true,
        });
        const prompt = await neo.exec('cat /agents/neo/CLAUDE.md');
        expect(prompt.stdout).toMatch(`
            # neo — worker in world "world-neo-{{hex#world}}"

            ## Identity

            Your soul is the source of truth for who you are. Read it first, every session.

            @SOUL.md

            ## Physics

            ### Laws
            - Network: bridge (outbound access enabled)
            - Filesystem is ephemeral except /workspaces and /agents

            ### Topology
            /agents/<your-name>/ - your home: SOUL.md, playbooks/, journal/ (read-write, persists across worlds)
            /workspaces/         - host project dirs mounted read-write, your actual work surface
            /world/              - world-shared state: knowledge/, inbox/<name>/ (read-write)
            /tmp                 - ephemeral scratch

            ### Communication
            Agents communicate via the inbox at /world/inbox/.
            To send a message: write a file to /world/inbox/{recipient}/.
            To check your inbox: read files from /world/inbox/{your-name}/.

            ## Faculties

            ### Tools
            spwn:unix, spwn:git, spwn:claude-code

            ## Roster

            The agents currently deployed in this world. Regenerated by spwn whenever the roster changes.

            ### Members
            - **neo** (worker)

            ### Where to find each member
            - Soul: \`/agents/<name>/SOUL.md\`
            - Playbooks: \`/agents/<name>/playbooks/\`
            - Journal: \`/agents/<name>/journal/\`
            - Inbox (this world): \`/world/inbox/<name>/\`

            Shared world knowledge (facts about the domain, not about any one agent) lives at \`/world/knowledge/\` — read and write freely; it's committed to the project.

            ## Role here

            You are deployed as a worker in world-neo-{{hex#world}}.

            ## Conventions

            1. **Read your soul first** every session. It shapes your voice, values, and priorities.
            2. **Mind lives at \`/agents/neo/\`**:
               - \`SOUL.md\` — who you are (edit freely to grow).
               - \`playbooks/\` — reusable procedures. Add a \`name:\`/\`description:\` header to any playbook to have it indexed in this prompt as a shortcut.
               - \`journal/\` — session history; auto-appended by the system.
            3. **Messaging** — send with \`/world/inbox/<their-name>/<timestamp>-from-neo.md\`; check yours at \`/world/inbox/neo/\`.
            4. **World knowledge** — save durable facts about this project or its domain to \`/world/knowledge/\`. Committed to the project; every agent in this world sees it.
            5. **Evolve** — when asked to dream, analyze the journal and promote recurring patterns to playbooks.

        `);
    });

    test('the agent finds its Claude Code onboarding done and its two roots trusted', async () => {
        // Given - the docker-pilot project brought up
        await using result = await cli
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .exec('up');

        // Then - the runtime config the agent boots on, whole
        expect(result.exitCode).toBe(0);
        const neo = result.container('neo');
        expect({
            claudeJson: JSON.parse(neo.file('/agents/neo/.claude.json').content) as unknown,
            settings: JSON.parse(neo.file('/agents/neo/.claude/settings.json').content) as unknown,
        }).toStrictEqual({
            claudeJson: {
                hasCompletedOnboarding: true,
                projects: {
                    '/agents/neo': { hasTrustDialogAccepted: true },
                    '/workspaces': { hasTrustDialogAccepted: true },
                },
            },
            settings: { skipDangerousModePermissionPrompt: true },
        });
    });

    test('an up of a world the manifest does not declare is refused and leaves no container', async () => {
        // Given - an up naming a world spwn.yaml does not hold
        await using result = await cli
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .exec('up nonexistent-world');

        // Then - the refusal names the world and nothing runs
        expect(result.exitCode).toBe(1);
        expect(result.stderr).toMatch(
            '  ✗ Project                  world "nonexistent-world" is not defined in spwn.yaml\n    Check spwn.yaml or pick an existing world name\n\n',
        );
        expect(result.containerIds).toStrictEqual([]);
    });

    test('an up while another holds the world lock is refused and leaves no container', async () => {
        // Given - a lockfile a concurrent up has not released
        await using result = await cli
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .fixture(directory('./__fixtures__/lock-held/'))
            .exec('up neo');

        // Then - the refusal says an up is in progress and nothing runs
        expect(result.exitCode).toBe(1);
        expect(result.stderr).toMatch(
            '  ✗ Up in progress           another `spwn up` is spawning world "neo"\n    Wait for the other run to finish, or remove {{workdir}}/.spwn/.up.neo.lock if it is stale\n\n',
        );
        expect(result.containerIds).toStrictEqual([]);
    });

    test('a workspace path that does not exist is refused and leaves no container', async () => {
        // Given - worlds.neo mounting a host path that is not there
        await using result = await cli
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .fixture(directory('./__fixtures__/bad-workspace/'))
            .exec('up');

        // Then - the refusal names the path and nothing runs
        expect(result.exitCode).toBe(1);
        expect(result.stderr).toMatch(`

              ⬡ Waking neo

              Environment
                → Connecting to Docker…
                ✓ Docker                 connected
                → Checking credentials…
                ✓ Credentials            none · not configured
                ✗ Spawn failed           workspace /no/such/workspace not found.
            Check the path exists and is accessible
                  Check that the -w path exists

        `);
        expect(result.containerIds).toStrictEqual([]);
    });

    test('a second up of a running world adds no second world', async () => {
        // Given - the project brought up twice, then listed
        await using result = await cli
            .fixture(directory('../__fixtures__/docker-pilot/'))
            .exec(['up', 'up', 'world list --json']);

        // Then - one running world
        expect(result.exitCode).toBe(0);
        expect(result.json).toMatch({
            mode: 'project',
            worlds: [{ agents: ['neo'], name: 'neo', status: 'running' }],
        });
    });
});
