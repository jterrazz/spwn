const defaultAgentYAMLTmpl = `# Agent composition: the source of truth for the agent's packages
# and runtime. When the agent is deployed in a world alongside others,
# the union of every member's packages is what gets compiled into the
# resulting container.

name: __NAME__
description: A blank-slate agent; replace this one-liner with what __NAME__ is for.

runtime:
  backend: "spwn:claude-code"

dependencies:
  - "spwn:unix"
  - "spwn:git"
  - "spwn:python"
`

const defaultAgentMDTmpl = `# __NAME__

You are **__NAME__**, an agent running inside a Spwn world.

## Your soul

Before doing anything else, read your soul:

@SOUL.md

## Your world

The CLAUDE.md Spwn generates for you at spawn time inlines your
world's physics, tools, roster, and conventions, so you don't need to
go hunting for separate files. Workspaces live at ` + "`/workspaces/`" + `;
that's where your changes land.

## Conventions

1. Read your soul first. It shapes how you respond.
2. Save important discoveries to ` + "`/world/knowledge/`" + ` so the whole world remembers them next time (committed per-world, shared across agents).
3. After significant work, consider promoting a pattern to ` + "`./playbooks/`" + `. Add a ` + "`name:`" + ` / ` + "`description:`" + ` header to any playbook to have it auto-indexed in your CLAUDE.md as a shortcut.
4. Before committing changes, run the project's existing tests if they exist.
`

func renderTmpl(tmpl, name string) []byte {
	return []byte(strings.ReplaceAll(tmpl, "__NAME__", name))
}

// AgentInfo describes an agent's Mind structure.
type AgentInfo struct {
	Name   string              `json:"name"`
	Path   string              `json:"path"`
	Team   string              `json:"team,omitempty"`
	Layers map[string][]string `json:"layers"`
}

// AgentDir returns the path to ~/.spwn/agents/{name}/.
func AgentDir(name string) string {
	return filepath.Join(platform.AgentsDir(), name)
}

// Init scaffolds a new Mind (playbooks/ + journal/) plus SOUL.md
// at the agent root. Skills used to be a Mind layer but were
// retired: they are build-time dependencies resolved via
// skill/<name> in agent.yaml now.
func Init(name string) (string, error) {
	dir := AgentDir(name)
	files := platform.DataFiles()
	defer files.Close()
	if _, err := files.Stat(dir); err == nil {
		return "", fmt.Errorf("agent %q already exists", name)
	} else if !errors.Is(err, fs.ErrNotExist) {
		return "", err
	}

	for _, layer := range platform.MindLayers {
		if err := files.MkdirAll(filepath.Join(dir, layer), 0755); err != nil {
			return "", fmt.Errorf("create %s: %w", layer, err)
		}
	}

	soul := `# Default Soul

You are a Spwn agent - a persistent AI worker living inside an isolated world.

## Your Identity
- You have a Mind that persists across sessions (playbooks, journal)
- Your soul (this file) defines your purpose and values - you are reading it now
- You evolve through experience: dream to analyze tasks, learn from outcomes, update your playbooks

## Your World
- Your CLAUDE.md (generated by Spwn at spawn time) inlines the world's physics, tools, roster, and your role. Read it first.
- Your workspace is at /workspaces/

## Communication
- Check your inbox at /world/inbox/{your-name}/ for messages from other agents
- Send messages to other agents by writing to /world/inbox/{their-name}/
- Save important learnings about the project/domain to /world/knowledge/ (world-shared, committed to git)

## Behavior
- Be concise and action-oriented - execute tasks directly
- Use your full Unix shell access (bash, git, curl, etc.)
- Stay within the Laws - they describe what is physically possible
`
	soulPath := filepath.Join(dir, platform.SoulFileName)
	if err := files.WriteFile(soulPath, []byte(soul), 0644); err != nil {
		return "", fmt.Errorf("create soul: %w", err)
	}

	if err := files.WriteFile(filepath.Join(dir, "agent.yaml"), renderTmpl(defaultAgentYAMLTmpl, name), 0644); err != nil {
		return "", fmt.Errorf("create agent.yaml: %w", err)
	}
	if err := files.WriteFile(filepath.Join(dir, "AGENTS.md"), renderTmpl(defaultAgentMDTmpl, name), 0644); err != nil {
		return "", fmt.Errorf("create AGENTS.md: %w", err)
	}

	return dir, nil
}

// Validate checks that a Mind directory exists and has a SOUL.md.
func Validate(name string) error {
	dir := AgentDir(name)
	files := platform.DataFiles()
	defer files.Close()
	info, err := files.Stat(dir)
	if err != nil {
		return fmt.Errorf("agent %q not found", name)
	}
	if !info.IsDir() {
		return fmt.Errorf("agent %q is not a directory", name)
	}

	soulPath := filepath.Join(dir, platform.SoulFileName)
	if _, err := files.Stat(soulPath); err != nil {
		return fmt.Errorf("agent %q is missing %s", name, platform.SoulFileName)
	}
	return nil
}

// List returns all agents in ~/.spwn/agents/.
func List() ([]AgentInfo, error) {
	dir := platform.AgentsDir()
	files := platform.DataFiles()
	defer files.Close()
	entries, err := files.ReadDir(dir)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}

	var agents []AgentInfo
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		info, err := Inspect(e.Name())
		if err != nil {
			continue
		}
		agents = append(agents, *info)
	}
	return agents, nil
}

// LayerCount returns how many layers have at least one file.
func LayerCount(info *AgentInfo) int {
	count := 0
	for _, files := range info.Layers {
		if len(files) > 0 {
			count++
		}
	}
	return count
}
